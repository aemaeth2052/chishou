def set_jp(run, size=None, bold=None, color=None):
    run.font.name = JP_FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), JP_FONT)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color


def add_title(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_jp(r, size=18, bold=True)
    return p


def add_h(text, level=1):
    sizes = {1: 14, 2: 12}
    p = doc.add_paragraph()
    p.space_before = Pt(8)
    r = p.add_run(text)
    set_jp(r, size=sizes.get(level, 12), bold=True, color=RGBColor(0x1F, 0x3B, 0x6E))
    return p


def add_body(text):
    p = doc.add_paragraph(style="List Bullet")
    r = p.add_run(text)
    set_jp(r, size=10.5)
    return p


def add_para(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_jp(r, size=10.5)
    return p


